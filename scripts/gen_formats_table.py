"""Generate docs/FORMATS.md from the format registry and the conversion route table.

Usage: python scripts/gen_formats_table.py [--check]

With --check nothing is written; the exit code is 1 when docs/FORMATS.md is out of date.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from quince.core import formats
from quince.core.registry import Registry, discover

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "FORMATS.md"


def _labels(format_ids: list[str]) -> str:
    return ", ".join(formats.get(f).label for f in format_ids) or "—"


def render(registry: Registry | None = None) -> str:
    registry = registry or discover()
    table = registry.routes
    lines = [
        "# Formats",
        "",
        "<!-- Generated by scripts/gen_formats_table.py. Do not edit by hand. -->",
        "",
        "Every format Quince recognizes and the conversions it offers. File types are detected",
        "by extension and checked against the file content (`src/quince/core/filetype.py`).",
        "",
        f"{len(list(formats.all_formats()))} formats, {len(table)} conversion routes.",
    ]
    for category in formats.Category:
        lines += [
            "",
            f"## {category.label}",
            "",
            "| Format | Name | Extensions | MIME type | Converts to | Made from |",
            "|--------|------|------------|-----------|-------------|-----------|",
        ]
        for fmt in formats.in_category(category):
            exts = " ".join(f"`.{e}`" for e in fmt.extensions)
            lines.append(
                f"| {fmt.label} | {fmt.name} | {exts} | `{fmt.mime_type}` "
                f"| {_labels(table.targets(fmt.id))} | {_labels(table.sources(fmt.id))} |"
            )

    lines += [
        "",
        "## Routes",
        "",
        "| Route | Backend | Needs |",
        "|-------|---------|-------|",
    ]
    for routes in table.by_target().values():
        for route in routes:
            lines.append(f"| {route} | {route.backend} | {', '.join(route.all_requires) or '—'} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/gen_formats_table.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
