"""Write requirements.lock: the exact version of every package in the project .venv.

Usage: python scripts/lock_deps.py [--check]

Run it after a deliberate upgrade (``pip install -U ...``) once all tests pass. Setup and
CI install with ``pip install -c requirements.lock -e '.[dev]'``, so every machine gets
the same versions. With --check, the exit code is 1 when the lock and .venv differ.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "requirements.lock"
HEADER = (
    "# Exact versions of every Python package Quince is tested with.\n"
    "# Generated by scripts/lock_deps.py; install with:\n"
    "#   pip install -c requirements.lock -e '.[dev]'\n"
)


def freeze() -> str:
    env = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"}
    cmd = [sys.executable, "-m", "pip", "freeze", "--exclude-editable"]
    out = subprocess.run(
        [*cmd, "--disable-pip-version-check"],
        env=env,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    lines = sorted((ln for ln in out.splitlines() if "==" in ln), key=str.lower)
    return HEADER + "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the lock is out of date")
    args = parser.parse_args(argv)
    text = freeze()
    if args.check:
        if not LOCK.exists() or LOCK.read_text() != text:
            print("requirements.lock does not match .venv; run scripts/lock_deps.py")
            return 1
        return 0
    LOCK.write_text(text)
    print(f"wrote {LOCK.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
